
'''
“A diferença entre um número e sua terça parte é 20.”
Qual é esse número?

'''

# A diferença entre um número e sua terça parte é 20.
# x - (x / 3) = 20
# (3x - x) / 3 = 20
# 2x / 3 = 20
# 2x = 60
# x = 30

x = 30
terca_parte = x / 3
resultado = x - terca_parte

print(f"O número é {x}.")
print(f"Sua terça parte é {terca_parte}.")
print(f"A diferença entre {x} e {terca_parte} é {resultado}.")
