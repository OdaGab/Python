# Problema: "Quatro vezes um número subtraído de 8 é igual a 28."
#
# Equação:
# 4x - 8 = 28
#
# Resolvendo:
# 4x = 28 + 8
# 4x = 36
# x = 36 / 4
# x = 9

numero = 9

# Verificando a condição
resultado = (4 * numero) - 8

print(f"O número procurado é {numero}.")
print(f"Verificação: (4 * {numero}) - 8 = {resultado}.")
